pub(super) fn emit_tail(em: &mut Emitter) {
    let mut fx = FnCtx::new(1);
    let n = fx.local(I32);
    let m = fx.local(I32);
    let dst = fx.local(I32);
    let i = fx.local(I32);

    fx.op(I::LocalGet(0));
    fx.op(I::I32Load(ma(0, 2)));
    fx.op(I::I32Const(TAG_LIST));
    fx.op(I::I32Ne);
    fx.op(I::If(BlockType::Empty));
    fx.op(I::Unreachable);
    fx.op(I::End);
    fx.op(I::LocalGet(0));
    fx.op(I::I32Load(ma(4, 2)));
    fx.op(I::LocalTee(n));
    fx.op(I::I32Eqz);
    fx.op(I::If(BlockType::Empty));
    fx.op(I::Unreachable);
    fx.op(I::End);

    fx.op(I::LocalGet(n));
    fx.op(I::I32Const(1));
    fx.op(I::I32Sub);
    fx.op(I::LocalSet(m));

    fx.op(I::I32Const(8));
    fx.op(I::LocalGet(m));
    fx.op(I::I32Const(2));
    fx.op(I::I32Shl);
    fx.op(I::I32Add);
    fx.op(I::Call(em.h.alloc));
    fx.op(I::LocalSet(dst));
    fx.op(I::LocalGet(dst));
    fx.op(I::I32Const(TAG_LIST));
    fx.op(I::I32Store(ma(0, 2)));
    fx.op(I::LocalGet(dst));
    fx.op(I::LocalGet(m));
    fx.op(I::I32Store(ma(4, 2)));

    fx.op(I::I32Const(0));
    fx.op(I::LocalSet(i));
    fx.op(I::Block(BlockType::Empty));
    fx.op(I::Loop(BlockType::Empty));
    fx.op(I::LocalGet(i));
    fx.op(I::LocalGet(m));
    fx.op(I::I32GeU);
    fx.op(I::BrIf(1));

    fx.op(I::LocalGet(dst));
    fx.op(I::I32Const(8));
    fx.op(I::I32Add);
    fx.op(I::LocalGet(i));
    fx.op(I::I32Const(2));
    fx.op(I::I32Shl);
    fx.op(I::I32Add);

    fx.op(I::LocalGet(0));
    fx.op(I::I32Const(12));
    fx.op(I::I32Add);
    fx.op(I::LocalGet(i));
    fx.op(I::I32Const(2));
    fx.op(I::I32Shl);
    fx.op(I::I32Add);
    fx.op(I::I32Load(ma(0, 2)));
    fx.op(I::I32Store(ma(0, 2)));
    fx.op(I::LocalGet(i));
    fx.op(I::I32Const(1));
    fx.op(I::I32Add);
    fx.op(I::LocalSet(i));
    fx.op(I::Br(0));
    fx.op(I::End);
    fx.op(I::End);
    fx.op(I::LocalGet(dst));
    let t = em.ty_idx(vec![I32], vec![I32]);
    em.bodies.push((t, fx.finish()));
}

pub(super) fn emit_concat(em: &mut Emitter) {
    let mut fx = FnCtx::new(2);
    let la = fx.local(I32);
    let lb = fx.local(I32);
    let p = fx.local(I32);
    for arg in [0u32, 1u32] {
        fx.op(I::LocalGet(arg));
        fx.op(I::I32Load(ma(0, 2)));
        fx.op(I::I32Const(TAG_STR));
        fx.op(I::I32Ne);
        fx.op(I::If(BlockType::Empty));
        fx.op(I::Unreachable);
        fx.op(I::End);
    }
    fx.op(I::LocalGet(0));
    fx.op(I::I32Load(ma(4, 2)));
    fx.op(I::LocalSet(la));
    fx.op(I::LocalGet(1));
    fx.op(I::I32Load(ma(4, 2)));
    fx.op(I::LocalSet(lb));
    fx.op(I::I32Const(8));
    fx.op(I::LocalGet(la));
    fx.op(I::I32Add);
    fx.op(I::LocalGet(lb));
    fx.op(I::I32Add);
    fx.op(I::Call(em.h.alloc));
    fx.op(I::LocalTee(p));
    fx.op(I::I32Const(TAG_STR));
    fx.op(I::I32Store(ma(0, 2)));
    fx.op(I::LocalGet(p));
    fx.op(I::LocalGet(la));
    fx.op(I::LocalGet(lb));
    fx.op(I::I32Add);
    fx.op(I::I32Store(ma(4, 2)));
    fx.op(I::LocalGet(p));
    fx.op(I::I32Const(8));
    fx.op(I::I32Add);
    fx.op(I::LocalGet(0));
    fx.op(I::I32Const(8));
    fx.op(I::I32Add);
    fx.op(I::LocalGet(la));
    fx.op(I::MemoryCopy {
        src_mem: 0,
        dst_mem: 0,
    });
    fx.op(I::LocalGet(p));
    fx.op(I::I32Const(8));
    fx.op(I::I32Add);
    fx.op(I::LocalGet(la));
    fx.op(I::I32Add);
    fx.op(I::LocalGet(1));
    fx.op(I::I32Const(8));
    fx.op(I::I32Add);
    fx.op(I::LocalGet(lb));
    fx.op(I::MemoryCopy {
        src_mem: 0,
        dst_mem: 0,
    });
    fx.op(I::LocalGet(p));
    let t = em.ty_idx(vec![I32, I32], vec![I32]);
    em.bodies.push((t, fx.finish()));
}

