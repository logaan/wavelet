use super::*;

pub(super) fn emit_decode(em: &mut Emitter) {
    let mut fx = FnCtx::new(1);
    let scalar = fx.local(I32);
    let next = fx.local(I32);
    let end = fx.local(I32);
    fx.op(I::LocalGet(0));
    fx.op(I::I32Const(1));
    fx.op(I::I32Add);
    fx.op(I::LocalSet(next));
    fx.op(I::LocalGet(0));
    fx.op(I::I32Load8U(ma(0, 0)));
    fx.op(I::LocalTee(scalar));
    fx.op(I::I32Const(128));
    fx.op(I::I32GeU);
    fx.op(I::If(BlockType::Empty));
    fx.op(I::LocalGet(scalar));
    fx.op(I::I32Const(224));
    fx.op(I::I32LtU);
    fx.op(I::If(BlockType::Empty));
    utf8_prefix(&mut fx, scalar, end, 2, 31);
    fx.op(I::Else);
    fx.op(I::LocalGet(scalar));
    fx.op(I::I32Const(240));
    fx.op(I::I32LtU);
    fx.op(I::If(BlockType::Empty));
    utf8_prefix(&mut fx, scalar, end, 3, 15);
    fx.op(I::Else);
    utf8_prefix(&mut fx, scalar, end, 4, 7);
    fx.op(I::End);
    fx.op(I::End);
    begin_scan(&mut fx, next, end);
    fx.op(I::LocalGet(scalar));
    fx.op(I::I32Const(6));
    fx.op(I::I32Shl);
    fx.op(I::LocalGet(next));
    fx.op(I::I32Load8U(ma(0, 0)));
    fx.op(I::I32Const(63));
    fx.op(I::I32And);
    fx.op(I::I32Or);
    fx.op(I::LocalSet(scalar));
    fx.op(I::LocalGet(next));
    fx.op(I::I32Const(1));
    fx.op(I::I32Add);
    fx.op(I::LocalSet(next));
    end_scan(&mut fx);
    fx.op(I::End);
    fx.op(I::LocalGet(scalar));
    fx.op(I::LocalGet(next));
    let t = em.ty_idx(vec![I32], vec![I32, I32]);
    em.bodies.push((t, fx.finish()));
}

fn utf8_prefix(fx: &mut FnCtx, scalar: u32, end: u32, width: i32, mask: i32) {
    fx.op(I::LocalGet(0));
    fx.op(I::I32Const(width));
    fx.op(I::I32Add);
    fx.op(I::LocalSet(end));
    fx.op(I::LocalGet(scalar));
    fx.op(I::I32Const(mask));
    fx.op(I::I32And);
    fx.op(I::LocalSet(scalar));
}

pub(super) fn emit_lookup(em: &mut Emitter) {
    let mut fx = FnCtx::new(3);
    let low = fx.local(I32);
    let middle = fx.local(I32);
    let row = fx.local(I32);
    begin_scan(&mut fx, low, 2);
    fx.op(I::LocalGet(low));
    fx.op(I::LocalGet(2));
    fx.op(I::I32Add);
    fx.op(I::I32Const(1));
    fx.op(I::I32ShrU);
    fx.op(I::LocalTee(middle));
    fx.op(I::I32Const(12));
    fx.op(I::I32Mul);
    fx.op(I::LocalGet(1));
    fx.op(I::I32Add);
    fx.op(I::LocalSet(row));
    fx.op(I::LocalGet(0));
    fx.op(I::LocalGet(row));
    fx.op(I::I32Load(ma(0, 2)));
    fx.op(I::I32LtU);
    fx.op(I::If(BlockType::Empty));
    fx.op(I::LocalGet(middle));
    fx.op(I::LocalSet(2));
    fx.op(I::Else);
    fx.op(I::LocalGet(0));
    fx.op(I::LocalGet(row));
    fx.op(I::I32Load(ma(4, 2)));
    fx.op(I::I32GtU);
    fx.op(I::If(BlockType::Empty));
    fx.op(I::LocalGet(middle));
    fx.op(I::I32Const(1));
    fx.op(I::I32Add);
    fx.op(I::LocalSet(low));
    fx.op(I::Else);
    fx.op(I::LocalGet(row));
    fx.op(I::I32Load(ma(8, 2)));
    fx.op(I::Return);
    fx.op(I::End);
    fx.op(I::End);
    end_scan(&mut fx);
    fx.op(I::I32Const(0));
    let t = em.ty_idx(vec![I32, I32, I32], vec![I32]);
    em.bodies.push((t, fx.finish()));
}

pub(super) fn emit_following(em: &mut Emitter, context: Table) {
    let mut fx = FnCtx::new(2);
    let scalar = fx.local(I32);
    let class = fx.local(I32);
    begin_scan(&mut fx, 0, 1);
    fx.op(I::LocalGet(0));
    fx.op(I::Call(em.h.unicode_decode));
    fx.op(I::LocalSet(0));
    fx.op(I::LocalSet(scalar));
    lookup(&mut fx, &em.h, scalar, context);
    fx.op(I::LocalTee(class));
    fx.op(I::I32Const(2));
    fx.op(I::I32Ne);
    fx.op(I::If(BlockType::Empty));
    fx.op(I::LocalGet(class));
    fx.op(I::I32Const(1));
    fx.op(I::I32Eq);
    fx.op(I::Return);
    fx.op(I::End);
    end_scan(&mut fx);
    fx.op(I::I32Const(0));
    let t = em.ty_idx(vec![I32, I32], vec![I32]);
    em.bodies.push((t, fx.finish()));
}
